def _make_effnet_branch(input_shape, name_prefix, freeze=True):
    """Cabang EfficientNetB0 (pretrain ImageNet, strategi fine-tune ala CheXNet).

    NB: EfficientNetB0 sudah punya Rescaling(1/255)+Normalization built-in
    di dalam arsitekturnya sendiri, jadi input HARUS skala 0–255 — bukan
    preprocess_input eksternal seperti ResNet50. Karena preprocess_image()
    kita menghasilkan 0–1 (dipakai juga utk EDA/augmentasi viz), kita
    tambahkan Rescaling(BACKBONE_INPUT_SCALE) sebelum backbone dipanggil.
    """
    # NB: JANGAN kasih `name=` custom di sini. Keras's EfficientNetB0 memakai
    # argumen `name` untuk menyusun nama file bobot yang di-download
    # (mis. "efficientnetb0_ap_notop.h5"), padahal file yang benar-benar ada
    # di server Google Storage cuma "efficientnetb0_notop.h5" -> hasilnya
    # 403 Forbidden. Biarkan default dulu, rename SETELAH bobot ter-load.
    backbone = EfficientNetB0(weights=None, include_top=False,
                    input_shape=input_shape, name=f'efficientnetb0_{name_prefix}')
    weights_path = tf.keras.utils.get_file(
    'efficientnetb0_notop.h5',
    'https://storage.googleapis.com/keras-applications/efficientnetb0_notop.h5',
    cache_subdir='models')
    backbone.load_weights(weights_path)
    backbone._name = f'efficientnetb0_{name_prefix}'
    backbone.trainable = not freeze
    inp = layers.Input(shape=input_shape, name=f'input_{name_prefix}')
    x = layers.Rescaling(BACKBONE_INPUT_SCALE, name=f'rescale_{name_prefix}')(inp)
    x = backbone(x, training=False)
    x = layers.GlobalAveragePooling2D(name=f'gap_{name_prefix}')(x)
    x = layers.BatchNormalization(name=f'bn_{name_prefix}')(x)
    x = layers.Dense(256, activation='relu', name=f'dense_{name_prefix}', kernel_regularizer=regularizers.l2(0.0001))(x)
    x = layers.Dropout(0.3, name=f'drop_{name_prefix}')(x)
    return inp, x, backbone


def build_image_only(tab_dim, n_classes=N_CLASSES, img_size=IMG_SIZE, freeze=True):
    """B: Image-only Dual EfficientNetB0."""
    input_shape = img_size + (3,)
    inp_ap,  feat_ap,  bb_ap  = _make_effnet_branch(input_shape, 'ap', freeze)
    inp_lat, feat_lat, bb_lat = _make_effnet_branch(input_shape, 'lat', freeze)
    x = layers.Concatenate(name='img_concat')([feat_ap, feat_lat])
    x = layers.Dense(512, activation='relu', name='img_fused', kernel_regularizer=regularizers.l2(0.0001))(x)
    x = layers.BatchNormalization(name='bn1')(x)
    x = layers.Dropout(0.5)(x)

    x = layers.Dense(256, activation='relu', name='img_d2', kernel_regularizer=regularizers.l2(0.0001))(x)
    x = layers.BatchNormalization(name='bn2')(x)
    x = layers.Dropout(0.3)(x)

    x = layers.Dense(128, activation='relu', name='img_d3', kernel_regularizer=regularizers.l2(0.0001))(x)
    x = layers.BatchNormalization(name='bn3')(x)
    x = layers.Dropout(0.3)(x)

    x = layers.Dense(64, activation='relu', name='img_d4', kernel_regularizer=regularizers.l2(0.0001))(x)
    x = layers.BatchNormalization(name='bn4')(x)
    x = layers.Dropout(0.3)(x)
    out = layers.Dense(n_classes, activation='softmax', name='output', kernel_regularizer=regularizers.l2(0.0001))(x)
    return keras.Model(inputs=[inp_ap, inp_lat], outputs=out, name='Image_Only'), bb_ap, bb_lat


def _make_tab_branch(tab_dim):
    inp = layers.Input(shape=(tab_dim,), name='input_tab')
    t = layers.Dense(64, name='tab_d1', activation='relu')(inp)
    t = layers.BatchNormalization(name='tab_bn1')(t)
    t = layers.Dropout(0.5)(t)

    t = layers.Dense(32, activation='relu', name='tab_d2', kernel_regularizer=regularizers.l2(0.0001))(t)
    t = layers.BatchNormalization(name='tab_bn2')(t)
    t = layers.Dropout(0.3, name='tab_drop1')(t)
    #t = layers.Dense(128, activation='relu', name='tab_d2')(t)
    return inp, t


def build_multimodal_no_gating(tab_dim, n_classes=N_CLASSES, img_size=IMG_SIZE, freeze=True):
    """C: Multimodal — simple concat (tanpa gating)."""
    input_shape = img_size + (3,)
    inp_ap,  feat_ap,  bb_ap  = _make_effnet_branch(input_shape, 'ap', freeze)
    inp_lat, feat_lat, bb_lat = _make_effnet_branch(input_shape, 'lat', freeze)
    img = layers.Concatenate(name='img_concat')([feat_ap, feat_lat])
    img = layers.Dense(512, activation='relu', name='img_fused', kernel_regularizer=regularizers.l2(0.0001))(img)
    img = layers.BatchNormalization(name='bn_img1')(img)
    img = layers.Dropout(0.5, name='drop_img1')(img)

    img = layers.Dense(256, activation='relu', name='img_fused2', kernel_regularizer=regularizers.l2(0.0001))(img)
    img = layers.BatchNormalization(name='bn_img2')(img)
    img = layers.Dropout(0.3, name='drop_img2')(img)

    img = layers.Dense(128, activation='relu', name='img_fused3', kernel_regularizer=regularizers.l2(0.0001))(img)
    img = layers.BatchNormalization(name='bn_img3')(img)
    img = layers.Dropout(0.3, name='drop_img3')(img)

    img = layers.Dense(64, activation='relu', name='img_fused4', kernel_regularizer=regularizers.l2(0.0001))(img)
    img = layers.BatchNormalization(name='bn_img4')(img)
    img = layers.Dropout(0.3, name='drop_img4')(img)

    inp_tab, t = _make_tab_branch(tab_dim)
    fusion = layers.Concatenate(name='mm_concat')([img, t])

    #x = layers.Dense(256, activation='relu', name='fusion_d256', kernel_regularizer=regularizers.l2(0.0001))(fusion)
    #x = layers.BatchNormalization(name='fusion_bn256')(x)
    #x = layers.Dropout(0.3, name='fusion_drop256')(x)

    x = layers.Dense(128, activation='relu', name='fusion_d64128', kernel_regularizer=regularizers.l2(0.0001))(fusion)
    x = layers.BatchNormalization(name='fusion_bn64128')(x)
    x = layers.Dropout(0.3, name='fusion_drop64128')(x)

    x = layers.Dense(64, activation='relu', name='fusion_d64', kernel_regularizer=regularizers.l2(0.0001))(x)
    x = layers.BatchNormalization(name='fusion_bn64')(x)
    x = layers.Dropout(0.3, name='fusion_drop64')(x)

    out = layers.Dense(n_classes, activation='softmax', name='output', kernel_regularizer=regularizers.l2(0.0001))(x)
    return keras.Model(inputs=[inp_ap, inp_lat, inp_tab], outputs=out,
                       name='Multimodal_NoGating'), bb_ap, bb_lat


def build_multimodal_gating(tab_dim, n_classes=N_CLASSES, img_size=IMG_SIZE, freeze=True):
    """
    D: Multimodal — Cross-Modal Gated Interaction.

    Alih-alih concatenate mentah (risiko satu modalitas mendominasi
    yang lain), network menjalankan gated cross-attention: setiap
    modalitas menghasilkan gate berdasarkan INFORMASI GABUNGAN kedua
    modalitas, lalu saling menge-scale kontribusi masing-masing
    SEBELUM fusion akhir — bukan sesudahnya.
    """
    input_shape = img_size + (3,)
    inp_ap,  feat_ap,  bb_ap  = _make_effnet_branch(input_shape, 'ap', freeze)
    inp_lat, feat_lat, bb_lat = _make_effnet_branch(input_shape, 'lat', freeze)

    # ── Cabang Citra — dense progression smooth: 512 → 256 → 128 - 64 ──────────
    img = layers.Concatenate(name='img_concat')([feat_ap, feat_lat])
    img = layers.Dense(512, activation='relu', name='img_d512', kernel_regularizer=regularizers.l2(0.0001))(img)
    img = layers.BatchNormalization(name='img_bn512')(img)
    img = layers.Dropout(0.5, name='img_drop512')(img)

    img = layers.Dense(256, activation='relu', name='img_d256', kernel_regularizer=regularizers.l2(0.0001))(img)
    img = layers.BatchNormalization(name='img_bn256')(img)
    img = layers.Dropout(0.3, name='img_drop256')(img)

    img = layers.Dense(128, activation='relu', name='img_d128', kernel_regularizer=regularizers.l2(0.0001))(img)
    img = layers.BatchNormalization(name='img_bn128')(img)
    img = layers.Dropout(0.3, name='img_drop128')(img)

    img = layers.Dense(64, activation='relu', name='img_d64', kernel_regularizer=regularizers.l2(0.0001))(img)
    img = layers.BatchNormalization(name='img_bn64')(img)
    img = layers.Dropout(0.3, name='img_drop64')(img)
    h_img = layers.Dense(64, activation='relu', name='h_img', kernel_regularizer=regularizers.l2(0.0001))(img)     # h_img ∈ R^64

    # ── Cabang Tabular — samakan dimensi output dgn h_img (utk gating) ────
    inp_tab, t = _make_tab_branch(tab_dim)
    #t = layers.Dense(32, activation='relu', name='tab_d64', kernel_regularizer=regularizers.l2(0.0001))(t)
    #h_tab = layers.Dense(32, activation='relu', name='h_tab', kernel_regularizer=regularizers.l2(0.0001))(t)       # h_tab ∈ R^64
    h_tab = t
    # ══════════════════════════════════════════════════════════════════
    #  CROSS-MODAL GATED INTERACTION
    # ══════════════════════════════════════════════════════════════════
    joint = layers.Concatenate(name='joint_concat')([h_img, h_tab])    # R^128 — "lihat dulu keduanya"

    gate_img = layers.Dense(64, activation='sigmoid', name='gate_img')(joint)
    gate_tab = layers.Dense(32, activation='sigmoid', name='gate_tab')(joint)

    h_img_gated = layers.Multiply(name='img_gated')([h_img, gate_img])
    h_tab_gated = layers.Multiply(name='tab_gated')([h_tab, gate_tab])

    fusion = layers.Concatenate(name='cross_gated_fusion')([h_img_gated, h_tab_gated])  # R^96

    # ── Head akhir — smooth juga: 256 → 64 ─────────────────────────────────
    #x = layers.Dense(256, activation='relu', name='fusion_d256', kernel_regularizer=regularizers.l2(0.0001))(fusion)
    #x = layers.BatchNormalization(name='fusion_bn256')(x)
    #x = layers.Dropout(0.3, name='fusion_drop256')(x)

    x = layers.Dense(128, activation='relu', name='fusion_d64128', kernel_regularizer=regularizers.l2(0.0001))(fusion)
    x = layers.BatchNormalization(name='fusion_bn64128')(x)
    x = layers.Dropout(0.3, name='fusion_drop64128')(x)

    x = layers.Dense(64, activation='relu', name='fusion_d64', kernel_regularizer=regularizers.l2(0.0001))(x)
    x = layers.BatchNormalization(name='fusion_bn64')(x)
    x = layers.Dropout(0.3, name='fusion_drop64')(x)

    out = layers.Dense(n_classes, activation='softmax', name='output', kernel_regularizer=regularizers.l2(0.0001))(x)
    return keras.Model(inputs=[inp_ap, inp_lat, inp_tab], outputs=out,
                       name='Multimodal_CrossGated'), bb_ap, bb_lat


