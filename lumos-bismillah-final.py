# ══════════════════════════════════════════════════════════════════════════
class MacroOsteopeniaF1Checkpoint(keras.callbacks.Callback):
    """Simpan model berdasarkan kombinasi macro-F1 dan F1 kelas osteopenia,
    bukan val_accuracy saja — supaya checkpoint yang disimpan benar-benar
    kuat di kelas minoritas osteopenia, bukan cuma akurasi keseluruhan."""

    def __init__(self, val_gen, y_val, filepath,
                 osteopenia_idx=LABEL_MAP['osteopenia'],
                 w_macro=0.60, w_osteopenia=0.40):
        super().__init__()
        self.val_gen = val_gen
        self.y_val = np.asarray(y_val)
        self.filepath = filepath
        self.osteopenia_idx = osteopenia_idx
        self.w_macro = w_macro
        self.w_osteopenia = w_osteopenia
        self.best_score = -np.inf

    def on_epoch_end(self, epoch, logs=None):
        logs = logs or {}
        y_prob = self.model.predict(self.val_gen, verbose=0)
        y_pred = np.argmax(y_prob, axis=1)

        macro_f1 = f1_score(self.y_val, y_pred, average='macro', zero_division=0)
        per_class_f1 = f1_score(self.y_val, y_pred, average=None,
                                 labels=np.arange(N_CLASSES), zero_division=0)
        osteopenia_f1 = per_class_f1[self.osteopenia_idx]

        # Kombinasi ini menjaga performa keseluruhan, tetapi memberi tekanan
        # ekstra ke osteopenia (kelas yang paling sering under-detected).
        score = (self.w_macro * macro_f1) + (self.w_osteopenia * osteopenia_f1)
        logs['val_macro_f1'] = macro_f1
        logs['val_osteopenia_f1'] = osteopenia_f1
        logs['val_macro_osteopenia_score'] = score

        print(f'\nval_macro_f1: {macro_f1:.4f} - val_osteopenia_f1: {osteopenia_f1:.4f} '
              f'- macro_osteopenia_score: {score:.4f}')

        if score > self.best_score:
            self.best_score = score
            self.model.save(self.filepath)
            print(f'✅ Model terbaik (macro-F1 + F1-osteopenia) disimpan ke {self.filepath}')

